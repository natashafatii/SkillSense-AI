}

ThemeData auroraTheme(AuroraTokens t, Brightness brightness) => ThemeData(
  useMaterial3: true,
  brightness: brightness,
  scaffoldBackgroundColor: t.bg,
  colorScheme: ColorScheme.fromSeed(
    seedColor: t.gd,
    brightness: brightness,
    surface: t.bg,
  ),
  fontFamily: 'Inter',
  extensions: [t],
  textTheme: TextTheme(
    bodyMedium: TextStyle(color: t.tx, fontSize: 12),
    bodySmall: TextStyle(color: t.tx2, fontSize: 11),
  ),
  inputDecorationTheme: InputDecorationTheme(
    isDense: true,
    filled: true,
    fillColor: t.field,
    hintStyle: TextStyle(color: t.tx3, fontSize: 11),
    contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 13),
    enabledBorder: OutlineInputBorder(
      borderRadius: BorderRadius.circular(10),
      borderSide: BorderSide(color: t.edge),
    ),
    focusedBorder: OutlineInputBorder(
      borderRadius: BorderRadius.circular(10),
      borderSide: BorderSide(color: t.gd),
    ),
  ),
);
